CREATE OR REPLACE FUNCTION public.resolve_streak(p_completed_today boolean DEFAULT false)
 RETURNS TABLE(streak integer, streak_best integer, froze boolean, broke boolean, lost integer, freeze_available boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  uid TEXT := auth.user_id();
  p RECORD;
  gap INTEGER;
  new_streak INTEGER;
  did_freeze BOOLEAN := FALSE;
  did_break BOOLEAN := FALSE;
  lost_days INTEGER := 0;
  this_month DATE := date_trunc('month', CURRENT_DATE)::date;
  can_freeze BOOLEAN;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'not authenticated'; END IF;

  SELECT pr.streak, pr.streak_day, pr.streak_best, pr.freeze_month
    INTO p
  FROM profiles pr WHERE pr.id = uid;

  can_freeze := (p.freeze_month IS NULL OR p.freeze_month < this_month);
  new_streak := COALESCE(p.streak, 0);

  IF p.streak_day IS NULL THEN
    -- never completed a day
    new_streak := CASE WHEN p_completed_today THEN 1 ELSE 0 END;

  ELSIF p.streak_day = CURRENT_DATE THEN
    -- already counted today; nothing to decide
    NULL;

  ELSE
    gap := CURRENT_DATE - p.streak_day;

    IF gap = 1 THEN
      -- yesterday: the streak survives, and grows if today is done
      IF p_completed_today THEN new_streak := new_streak + 1; END IF;

    ELSIF gap = 2 AND can_freeze AND COALESCE(p.streak, 0) > 0 THEN
      -- exactly one missed day, and a freeze is available
      did_freeze := TRUE;
      UPDATE profiles SET freeze_month = this_month WHERE id = uid;
      IF p_completed_today THEN new_streak := new_streak + 1; END IF;

    ELSE
      -- the streak is gone
      IF COALESCE(p.streak, 0) > 0 THEN
        did_break := TRUE;
        lost_days := p.streak;
      END IF;
      new_streak := CASE WHEN p_completed_today THEN 1 ELSE 0 END;
    END IF;
  END IF;

  UPDATE profiles pr
     SET streak      = new_streak,
         streak_best = GREATEST(COALESCE(pr.streak_best, 0), new_streak),
         streak_day  = CASE WHEN p_completed_today THEN CURRENT_DATE ELSE pr.streak_day END,
         streak_broken_at = CASE WHEN did_break THEN CURRENT_DATE ELSE pr.streak_broken_at END
   WHERE pr.id = uid;

  RETURN QUERY
  SELECT new_streak,
         (SELECT pr.streak_best FROM profiles pr WHERE pr.id = uid),
         did_freeze,
         did_break,
         lost_days,
         (SELECT (pr.freeze_month IS NULL OR pr.freeze_month < this_month)
          FROM profiles pr WHERE pr.id = uid);
END;
$function$;

CREATE OR REPLACE FUNCTION public.respond_channel_request(p_channel bigint, p_user text, p_accept boolean)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  IF NOT is_channel_admin(p_channel) THEN RETURN false; END IF;

  IF p_accept THEN
    INSERT INTO channel_members (channel_id, user_id, role)
    VALUES (p_channel, p_user, 'member')
    ON CONFLICT DO NOTHING;
    UPDATE channel_requests SET state = 'accepted'
      WHERE channel_id = p_channel AND user_id = p_user;
    UPDATE channels SET members_count = (
      SELECT COUNT(*) FROM channel_members WHERE channel_id = p_channel
    ) WHERE id = p_channel;

    INSERT INTO notifications (user_id, actor_id, kind, text)
    VALUES (p_user, auth.user_id(), 'channel_accepted',
            (SELECT name FROM channels WHERE id = p_channel));
  ELSE
    UPDATE channel_requests SET state = 'declined'
      WHERE channel_id = p_channel AND user_id = p_user;
  END IF;
  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.respond_follow_request(p_actor text, p_accept boolean)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE v_me text := auth.user_id();
BEGIN
  IF v_me IS NULL THEN RETURN false; END IF;

  IF p_accept THEN
    UPDATE follows SET state = 'accepted'
     WHERE follower_id = p_actor AND followee_id = v_me;
    RETURN FOUND;                    -- triggers above do the rest
  END IF;

  DELETE FROM follows
   WHERE follower_id = p_actor AND followee_id = v_me;
  RETURN true;
END;
$function$;

-- route_new_message() — Sends a first message from a stranger to dm_requests
-- instead of the inbox.
CREATE OR REPLACE FUNCTION public.route_new_message()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  existing dm_requests%ROWTYPE;
  sent_count INTEGER;
BEGIN
  -- Talking to yourself is always allowed and never a request.
  IF NEW.sender_id = NEW.receiver_id THEN
    RETURN NEW;
  END IF;

  -- Connected already, or the receiver previously accepted: nothing to do.
  IF dm_connected(NEW.sender_id, NEW.receiver_id) THEN
    RETURN NEW;
  END IF;

  SELECT * INTO existing
  FROM dm_requests
  WHERE owner_id = NEW.receiver_id AND peer_id = NEW.sender_id;

  IF FOUND AND existing.state = 'accepted' THEN
    RETURN NEW;
  END IF;

  IF FOUND AND existing.state = 'declined' THEN
    -- Declined is a quiet wall. The insert is dropped and the sender
    -- sees their own message locally with no error — exactly what
    -- Instagram does. Telling them would defeat the purpose.
    RETURN NULL;
  END IF;

  IF NOT FOUND THEN
    INSERT INTO dm_requests (owner_id, peer_id, state)
    VALUES (NEW.receiver_id, NEW.sender_id, 'pending')
    ON CONFLICT DO NOTHING;
    RETURN NEW;
  END IF;

  -- Pending: cap the number of unanswered messages.
  SELECT COUNT(*) INTO sent_count
  FROM messages
  WHERE sender_id = NEW.sender_id AND receiver_id = NEW.receiver_id;

  IF sent_count >= 3 THEN
    RETURN NULL;
  END IF;

  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.set_channel_role(p_channel bigint, p_user text, p_role text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  IF channel_role(p_channel, auth.user_id()) <> 'owner' THEN RETURN false; END IF;
  IF p_role NOT IN ('admin', 'member') THEN RETURN false; END IF;
  -- Ownership is not transferable through this call.
  IF channel_role(p_channel, p_user) = 'owner' THEN RETURN false; END IF;

  UPDATE channel_members SET role = p_role
   WHERE channel_id = p_channel AND user_id = p_user;
  RETURN FOUND;
END;
$function$;

