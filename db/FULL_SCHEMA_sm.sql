CREATE OR REPLACE FUNCTION public.is_admin()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM profiles
    WHERE id = auth.user_id() AND role = 'admin' AND status = 'approved'
  );
$function$;

-- is_approved() — Gate for every write. Only 'rejected' and 'banned' are refused —
-- an account is usable the moment it is created.
CREATE OR REPLACE FUNCTION public.is_approved()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM profiles
    WHERE id = auth.user_id()
      AND coalesce(status,'approved') NOT IN ('rejected','banned')
  );
$function$;

CREATE OR REPLACE FUNCTION public.blocked_between(a text, b text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM blocks
    WHERE (blocker_id = a AND blocked_id = b)
       OR (blocker_id = b AND blocked_id = a)
  );
$function$;

-- can_view() — Private-account logic, used by the read policies.
CREATE OR REPLACE FUNCTION public.can_view(target text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
AS $function$
  SELECT
    target = auth.user_id()
    OR is_admin()
    OR (
      NOT blocked_between(auth.user_id(), target)
      AND (
        NOT (SELECT is_private FROM profiles WHERE id = target)
        OR EXISTS (
          SELECT 1 FROM follows
          WHERE follower_id = auth.user_id()
            AND followee_id = target
            AND state = 'accepted'
        )
      )
    );
$function$;

CREATE OR REPLACE FUNCTION public.dm_connected(a text, b text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM follows
    WHERE state = 'accepted'
      AND ((follower_id = a AND followee_id = b)
        OR (follower_id = b AND followee_id = a))
  );
$function$;

-- award_xp() — The ONLY way XP can move. SECURITY DEFINER, so it bypasses the
-- guard trigger that blocks students writing profiles.xp by hand.
CREATE OR REPLACE FUNCTION public.award_xp(p_kind text, p_amount integer, p_ref_type text DEFAULT NULL::text, p_ref_id text DEFAULT NULL::text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  uid TEXT := auth.user_id();
  inserted INTEGER := 0;
  new_total INTEGER;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'not authenticated'; END IF;

  -- A negative or absurd amount can only be a bug or an attack.
  IF p_amount < 0 OR p_amount > 100 THEN
    RAISE EXCEPTION 'invalid xp amount %', p_amount;
  END IF;

  INSERT INTO xp_events (user_id, kind, amount, ref_type, ref_id)
  VALUES (uid, p_kind, p_amount, p_ref_type, p_ref_id)
  ON CONFLICT DO NOTHING;

  GET DIAGNOSTICS inserted = ROW_COUNT;

  IF inserted > 0 THEN
    UPDATE profiles SET xp = xp + p_amount WHERE id = uid
    RETURNING xp INTO new_total;
  ELSE
    SELECT xp INTO new_total FROM profiles WHERE id = uid;
  END IF;

  RETURN new_total;
END;
$function$;

CREATE OR REPLACE FUNCTION public.can_message(p_user text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
AS $function$
  SELECT
    p_user <> auth.user_id()
    AND NOT blocked_between(auth.user_id(), p_user)
    AND EXISTS (SELECT 1 FROM profiles WHERE id = p_user AND status = 'approved')
    AND NOT EXISTS (
      SELECT 1 FROM dm_requests
      WHERE owner_id = p_user AND peer_id = auth.user_id() AND state = 'declined'
    );
$function$;

CREATE OR REPLACE FUNCTION public.can_post_group(p_channel bigint, p_event bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT CASE
    WHEN p_event IS NOT NULL THEN is_event_attendee(p_event)
    WHEN p_channel IS NOT NULL THEN
      is_channel_member(p_channel)
      AND (
        is_channel_admin(p_channel)
        OR COALESCE((SELECT post_policy FROM channels WHERE id = p_channel), 'all') = 'all'
      )
    ELSE false
  END;
$function$;

CREATE OR REPLACE FUNCTION public.channel_owner_member()
 RETURNS trigger
