-- ----------------------------------------------------------
-- 1. MEDIA SIZE GUARD
--
-- Media is stored in Postgres as data: URLs, so every media column
-- carries a CHECK that calls this. It must exist before the tables.
-- ----------------------------------------------------------
CREATE OR REPLACE FUNCTION public.media_ok(v text, max_bytes integer)
 RETURNS boolean
 LANGUAGE sql
 IMMUTABLE
AS $function$
  SELECT v IS NULL
      OR (
        octet_length(v) <= max_bytes
        AND (v LIKE 'data:image/%' OR v LIKE 'data:video/%'
             OR v LIKE 'data:audio/%' OR v LIKE 'http://%' OR v LIKE 'https://%')
      );
$function$;

