CREATE OR REPLACE FUNCTION public.track_name_change()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
  window_days CONSTANT INTEGER := 15;
BEGIN
  IF NEW.full_name IS DISTINCT FROM OLD.full_name THEN
    IF OLD.name_changed_at IS NULL
       OR OLD.name_changed_at < now() - (window_days || ' days')::interval THEN
      NEW.name_change_count := 1;          -- window expired, start over
    ELSE
      NEW.name_change_count := COALESCE(OLD.name_change_count, 0) + 1;
    END IF;
    NEW.name_changed_at := now();
  END IF;
  RETURN NEW;
END;
$function$;

-- track_quest() — The ONLY way quest progress can move.
-- NOTE the `#variable_conflict use_column`: the RETURNS TABLE output
-- names (quest_id, progress, target) collide with the table's own
-- columns, and without this every call failed with
-- "column reference quest_id is ambiguous".
CREATE OR REPLACE FUNCTION public.track_quest(p_quest_id text, p_target integer, p_amount integer DEFAULT 1)
 RETURNS TABLE(quest_id text, progress integer, target integer, just_done boolean, day_complete boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
#variable_conflict use_column
DECLARE
  uid          TEXT := auth.user_id();
  was_done     BOOLEAN;
  row_progress INTEGER;
  row_target   INTEGER;
  now_done     BOOLEAN;
  all_done     BOOLEAN;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'not authenticated'; END IF;

  INSERT INTO quests (user_id, day, quest_id, progress, target)
  VALUES (uid, CURRENT_DATE, p_quest_id, 0, p_target)
  ON CONFLICT (user_id, day, quest_id) DO NOTHING;

  SELECT (q.done_at IS NOT NULL) INTO was_done
    FROM quests q
   WHERE q.user_id = uid AND q.day = CURRENT_DATE AND q.quest_id = p_quest_id;

  UPDATE quests q
     SET progress = LEAST(q.target, q.progress + p_amount),
         done_at  = CASE WHEN q.done_at IS NULL
                          AND q.progress + p_amount >= q.target
                         THEN now() ELSE q.done_at END
   WHERE q.user_id = uid AND q.day = CURRENT_DATE AND q.quest_id = p_quest_id
   RETURNING q.progress, q.target, (q.done_at IS NOT NULL)
        INTO row_progress, row_target, now_done;

  SELECT COUNT(*) = 0 INTO all_done
    FROM quests q
   WHERE q.user_id = uid AND q.day = CURRENT_DATE AND q.done_at IS NULL;

  RETURN QUERY SELECT p_quest_id, row_progress, row_target,
                      (now_done AND NOT COALESCE(was_done, FALSE)),
                      all_done;
END;
$function$;
