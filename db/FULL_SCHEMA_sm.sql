CREATE OR REPLACE FUNCTION public.notify_new_follow()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_kind text;
BEGIN
  -- Following yourself is not an event.
  IF NEW.follower_id = NEW.followee_id THEN RETURN NEW; END IF;

  v_kind := CASE WHEN NEW.state = 'accepted' THEN 'follow' ELSE 'request' END;

  -- One row per (person, kind). Un-following and re-following ten times
  -- must not produce ten lines in the shade. Re-requesting after a
  -- refusal moves the existing row forward instead.
  IF EXISTS (
    SELECT 1 FROM notifications
    WHERE user_id  = NEW.followee_id
      AND actor_id = NEW.follower_id
      AND kind     = v_kind
      AND read_at IS NULL
  ) THEN
    UPDATE notifications
       SET created_at = now()          -- so pending_alerts(p_since) sees it
     WHERE user_id  = NEW.followee_id
       AND actor_id = NEW.follower_id
       AND kind     = v_kind
       AND read_at IS NULL;
  ELSE
    INSERT INTO notifications (user_id, actor_id, kind)
    VALUES (NEW.followee_id, NEW.follower_id, v_kind);
  END IF;

  RETURN NEW;

EXCEPTION WHEN OTHERS THEN
  -- Losing the FOLLOW because the notification failed would be a far
  -- worse bug than a missing notification.
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.notify_new_message()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_kind      text := 'message';
  v_muted     boolean := false;
  v_preview   text;
  v_recent_id bigint;
BEGIN
  -- Never notify yourself. Saved-messages-to-self is a real pattern.
  IF NEW.sender_id = NEW.receiver_id THEN
    RETURN NEW;
  END IF;

  -- Respect a muted conversation. The column may not exist on older
  -- deployments, so this is wrapped rather than assumed.
  BEGIN
    SELECT COALESCE(muted, false) INTO v_muted
    FROM dm_threads
    WHERE owner_id = NEW.receiver_id AND peer_id = NEW.sender_id;
  EXCEPTION WHEN undefined_table OR undefined_column THEN
    v_muted := false;
  END;

  IF v_muted THEN
    RETURN NEW;
  END IF;

  -- A first message from a stranger is a REQUEST, not a message. It
  -- gets its own channel in the APK so it can be quieter.
  BEGIN
    IF NOT dm_connected(NEW.sender_id, NEW.receiver_id) THEN
      IF EXISTS (
        SELECT 1 FROM dm_requests
        WHERE owner_id = NEW.receiver_id
          AND peer_id  = NEW.sender_id
          AND state    = 'pending'
      ) THEN
        v_kind := 'dm_request';
      END IF;
    END IF;
  EXCEPTION WHEN undefined_function OR undefined_table THEN
    v_kind := 'message';
  END;

  v_preview := dm_preview(NEW.text, NEW.media_type);

  -- COALESCE, because a burst of twenty messages must be one line in
  -- the shade, not twenty buzzes. If an unread alert from this same
  -- sender already exists and is under two minutes old, move it forward
  -- instead of adding another row.
  SELECT id INTO v_recent_id
  FROM notifications
  WHERE user_id   = NEW.receiver_id
    AND actor_id  = NEW.sender_id
    AND kind      = v_kind
    AND read_at IS NULL
    AND created_at > now() - interval '2 minutes'
  ORDER BY created_at DESC
  LIMIT 1;

  IF v_recent_id IS NOT NULL THEN
    UPDATE notifications
       SET text       = v_preview,
           created_at = now()      -- so pending_alerts(p_since) sees it
     WHERE id = v_recent_id;
  ELSE
    INSERT INTO notifications (user_id, actor_id, kind, text)
    VALUES (NEW.receiver_id, NEW.sender_id, v_kind, v_preview);
  END IF;

  RETURN NEW;

EXCEPTION WHEN OTHERS THEN
  -- A failure here must NEVER lose the message itself. Delivering the
  -- message silently beats rejecting it because the alert failed.
  RETURN NEW;
END;
$function$;

